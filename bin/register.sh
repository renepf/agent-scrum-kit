#!/usr/bin/env bash
# Enter role + session id in roster.md and lock the role for THIS instance.
# At the start of every session, after every reset — tick.sh calls it itself when needed.
#
#   export KIT_ROLE=engineer-a
#   bin/register.sh                 # session id from the host adapter
#   bin/register.sh <session-id>    # or explicitly
#
# Twin lock (lease): one file per role, sprints/<active>/.lease-<role>, holding the
# session id, the host PID and a time. If ANOTHER living instance of the same role is
# already running, register.sh aborts. The reason: a session was resumed twice and two
# processes of the same role worked in parallel — owner:<role> separates roles, not twins.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

SPRINT="$(sprint_dir)"
R="$(role)"
SID="${1:-$(session_id)}"
ROSTER="$SPRINT/roster.md"
LEASE="$SPRINT/.lease-$R"
HPID="$(host_pid)"
NOW_EPOCH="$(date +%s)"

check_lease() {
  if [ -f "$LEASE" ]; then
    local l_sid l_pid l_epoch age
    IFS='|' read -r l_sid l_pid l_epoch < "$LEASE" || true
    age=$(( NOW_EPOCH - ${l_epoch:-0} ))
    if [ "$age" -lt $(( KIT_LEASE_MINUTES * 60 )) ] && host_alive "$l_pid"; then
      if [ -z "$HPID" ]; then
        echo "WARNING: host PID UNKNOWN (adapters/$KIT_HOST/host-pid.sh) — the twin lock cannot check whether PID $l_pid is the same instance." >&2
      elif [ "$l_pid" != "$HPID" ]; then
        die "second instance of '$R': host PID $l_pid (session $l_sid) is still running and ticked $((age / 60)) min ago. End this instance (PID $HPID, session $SID) — otherwise two processes of the same role work in parallel."
      fi
    fi
  fi
  printf '%s|%s|%s\n' "$SID" "${HPID:--}" "$NOW_EPOCH" | atomic_write "$LEASE"
}

write_roster() {
  local body
  body="$( { [ -f "$ROSTER" ] && grep '^| 2' "$ROSTER" | grep -v "^| [^|]* | $R | " || true; } )"
  {
    printf '# roster · %s\n\n' "$(basename "$SPRINT")"
    printf 'GENERATED by bin/register.sh. One line per role, the youngest entry counts.\n\n'
    printf '| Time | Role | Session-ID | Host | Host-PID |\n|---|---|---|---|---|\n'
    [ -n "$body" ] && printf '%s\n' "$body"
    printf '| %s | %s | %s | %s | %s |\n' "$(now)" "$R" "$SID" "$KIT_HOST" "${HPID:-UNKNOWN}"
  } | atomic_write "$ROSTER"
}

# Two locks, one after the other, never nested:
#   $LEASE.lock   — per role: two twins starting at the same moment do not both survive.
#   $ROSTER.lock  — for all roles: roster.md is shared. With only the role lock, nine sessions
#                   starting at once lost 5 of 9 lines (start test 2026-09-14).
# Not nested, because with_lock sets its cleanup trap: an inner lock overwrites the trap of the
# outer one, and a die() in the twin check then left the lease lock lying around.
with_lock "$LEASE.lock" check_lease
with_lock "$ROSTER.lock" write_roster
anchor_role "$R"

echo "$R registered · session $SID · host $KIT_HOST · pid ${HPID:-UNKNOWN}"
