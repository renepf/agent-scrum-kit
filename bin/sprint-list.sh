#!/usr/bin/env bash
# The local ticket list of the sprint: number, title, status, owner — nothing else.
#
# Owner decision 2026-09-29 (D50): planning happens on GitHub, the local side keeps a list of
# tickets and their current status. The board stays the truth; this file is a copy of it, so a
# role can read the sprint at a glance without asking GitHub again.
#
# One rebuild costs exactly ONE board call (`tickets.sh sprint` returns number, title and labels
# together), which is why status.sh can afford to rebuild after every transition.
#
# On a disagreement the board wins: the row is corrected and the difference is named in the file,
# under DEVIATION. With --expect-change <nr> that ticket is left out of the comparison — it is the
# one the caller has just moved, so its row is supposed to differ.
#
# A failed board read is a failure, not a state: the script exits non-zero and leaves the list
# exactly as it was.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

EXPECT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --expect-change) EXPECT="${2:-}"; shift 2 ;;
    *) die "usage: sprint-list.sh [--expect-change <ticket>]" ;;
  esac
done

SPRINT="$(sprint_dir)"
LIST="$SPRINT/tickets.md"

KIT_BOARD_JSON="$("$BIN_DIR/tickets.sh" sprint)" \
  || die "sprint tickets not readable — a failure, not a state"
export KIT_BOARD_JSON

NEW="$(python3 - "$LIST" "$(basename "$SPRINT")" "$EXPECT" "${KIT_OWNER_PREFIX:-owner:}" "${KIT_LABEL_PREFIX:-status:}" <<'PY'
import datetime, json, os, re, sys

list_path, sprint_name, expect, owner_prefix, status_prefix = sys.argv[1:6]
board = json.loads(os.environ["KIT_BOARD_JSON"])

def label(labels, prefix):
    for l in labels:
        name = l["name"] if isinstance(l, dict) else l
        if name.startswith(prefix):
            return name[len(prefix):]
    return ""

rows = {}
for i in board:
    labels = i.get("labels", [])
    rows[str(i["number"])] = (i.get("title", ""),
                              label(labels, status_prefix) or "—",
                              label(labels, owner_prefix) or "—")

# What the list said before. A missing file is not a disagreement — it is a first run.
old, had_list = {}, os.path.exists(list_path)
if had_list:
    for line in open(list_path, encoding="utf-8"):
        m = re.match(r"\|\s*#(\d+)\s*\|(.*?)\|(.*?)\|(.*?)\|", line)
        if m:
            old[m.group(1)] = tuple(x.strip() for x in m.groups()[1:])

deviations = []
if had_list:
    for nr, before in sorted(old.items(), key=lambda kv: int(kv[0])):
        if nr == expect:
            continue
        now = rows.get(nr)
        if now is None:
            deviations.append(f"#{nr} stood in the list as `{before[1]}` and is not on the board any more")
        elif now[1:] != before[1:]:
            deviations.append(f"#{nr} list `{before[1]}` owner `{before[2]}` → board `{now[1]}` owner `{now[2]}`")

out = [f"# tickets · {sprint_name}", ""]
out.append("GENERATED by bin/sprint-list.sh. Do not edit by hand — the board is the truth, a hand")
out.append("edit is overwritten at the next rebuild.")
out.append(f"As of: {datetime.datetime.now():%Y-%m-%d %H:%M} · read with one board call")
out.append("")
if deviations:
    out.append("DEVIATION — the local list disagreed with the board. The board wins, the rows below")
    out.append("are the board's:")
    out += [f"- {d}" for d in deviations]
    out.append("")
out.append("| # | Title | Status | Owner |")
out.append("|---|---|---|---|")
for nr in sorted(rows, key=int):
    title, status, owner = rows[nr]
    out.append(f"| #{nr} | {title} | {status} | {owner} |")
print("\n".join(out))
PY
)" || die "the list could not be built — the old one stays"

printf '%s\n' "$NEW" | atomic_write "$LIST"
echo "tickets.md written: $(printf '%s' "$NEW" | grep -c '^| #[0-9]') tickets"
