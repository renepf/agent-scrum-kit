#!/usr/bin/env bash
# Memory per role plus one shared swarm memory. Sprint-independent:
# survives a context reset, a session change and the end of a sprint. Rules: memory/README.md
#
#   memory/<role>/INDEX.md             GENERATED — everything this role knows
#   memory/<role>/log.md               append-only journal
#   memory/<role>/facts/<slug>.md      one fact per file (frontmatter)
#   memory/<role>/docs/<slug>.md       working notes, overwritable
#   memory/<role>/handover/<time>.md   handover before every reset
#   memory/_shared/INDEX.md            GENERATED — swarm knowledge
#   memory/_shared/facts/<slug>.md     shared fact, only the author changes or deletes it
#
#   brain.sh note <slug> "<description>"     < body   TYPE=user|feedback|project|reference
#   brain.sh share <slug> "<description>"    < body   (TYPE as above)
#   brain.sh forget <slug> [--shared]                 delete a fact that turned out wrong
#   brain.sh doc <slug> "<description>"      < body
#   brain.sh handover "<description>"        < body
#   brain.sh log "<subject>"                 < body
#   brain.sh recall                                   after a reset: index, last handover, swarm
#   brain.sh index                                    rebuild the indexes
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

R="$(role)"
ME="$MEMORY_DIR/$R"
SHARED="$MEMORY_DIR/_shared"
mkdir -p "$ME/facts" "$ME/docs" "$ME/handover" "$SHARED/facts"

slug_ok() { [[ "$1" =~ ^[a-z0-9][a-z0-9-]{1,60}$ ]] || die "slug '$1' invalid: only a-z, 0-9, hyphen, 2–61 characters"; }

# Checks a new fact against the rules in memory/README.md. The body comes through a file.
# Exit != 0 with a message when a rule is violated.
guard_fact() {
  local target="$1" slug="$2" desc="$3" type="$4" bodyfile="$5"
  python3 - "$MEMORY_DIR" "$target" "$slug" "$desc" "$type" "$bodyfile" <<'PY'
import glob, os, re, sys
mem, target, slug, desc, typ, bodyfile = sys.argv[1:7]
body = open(bodyfile, encoding="utf-8").read()

if typ not in ("user", "feedback", "project", "reference"):
    sys.exit(f"ERROR: type '{typ}' invalid. Allowed: user | feedback | project | reference")
if not desc.strip():
    sys.exit("ERROR: description missing — it is the line in the index, without it nobody finds the fact")

# Relative dates are wrong in three months. Write them absolute.
REL = r"\b(heute|gestern|morgen|vorgestern|(ue|ü)bermorgen|letzte[nr]? (woche|monat)|n(ae|ä)chste[nr]? (woche|monat)|diese[nr]? woche|today|yesterday|tomorrow|last (week|month)|next (week|month)|this week)\b"
m = re.search(REL, (desc + "\n" + body).lower())
if m:
    sys.exit(f"ERROR: relative date '{m.group(0)}' — rewrite it as an absolute date (YYYY-MM-DD)")

# Duplicate: ANOTHER slug with the same description. Overwriting the same slug is
# the intended way to change a fact.
norm = lambda s: re.sub(r"\s+", " ", s.strip().lower())
for f in glob.glob(os.path.join(mem, "*", "facts", "*.md")):
    if os.path.abspath(f) == os.path.abspath(target):
        continue
    for line in open(f, encoding="utf-8", errors="replace"):
        if line.startswith("description:") and norm(line[12:]) == norm(desc):
            rel = os.path.relpath(f, mem)
            sys.exit(f"ERROR: duplicate of memory/{rel} — change it there (same slug), do not create a second entry")
PY
}

write_fm() {
  local target="$1" name="$2" desc="$3" type="$4" bodyfile="$5"
  {
    printf -- '---\nname: %s\ndescription: %s\ntype: %s\nauthor: %s\nupdated: %s\n---\n\n' \
      "$name" "$desc" "$type" "$R" "$(date '+%Y-%m-%d %H:%M')"
    cat "$bodyfile"
  } | atomic_write "$target"
}

# Build the index of a folder from the frontmatter. Deterministic, atomic, never handwritten.
build_index() {
  local root="$1" title="$2"
  python3 - "$root" "$title" "$MEMORY_DIR" <<'PY' | atomic_write "$root/INDEX.md"
import glob, os, re, sys
root, title, mem = sys.argv[1], sys.argv[2], sys.argv[3]
def fm(path):
    meta, body = {}, []
    with open(path, encoding="utf-8", errors="replace") as fh:
        lines = fh.read().split("\n")
    if lines and lines[0].strip() == "---":
        for i, line in enumerate(lines[1:], 1):
            if line.strip() == "---":
                body = lines[i + 1:]
                break
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, "\n".join(body)

known = set()
for f in glob.glob(os.path.join(mem, "*", "facts", "*.md")):
    known.add(fm(f)[0].get("name", ""))

print(f"# {title}\n\nGENERATED by bin/brain.sh. Do not edit by hand. One line per entry.\n")
dangling = []
for kind, label in (("handover", "Handovers (newest first)"), ("facts", "Facts"), ("docs", "Working documents")):
    d = os.path.join(root, kind)
    if not os.path.isdir(d):
        continue
    files = sorted((f for f in os.listdir(d) if f.endswith(".md")), reverse=(kind == "handover"))
    if not files:
        continue
    # Handovers pile up: a role that resets every half hour has hundreds after a week. Unshortened
    # they push facts and documents out of every window that reads this index — `recall` showed
    # nothing but handover filenames, which is the opposite of what an external brain is for.
    # Nothing is deleted, only listed shorter, the same way the journal below is.
    total = len(files)
    shown = files[:20] if kind == "handover" else files
    heading = f"{label} — newest {len(shown)} of {total}" if len(shown) < total else label
    print(f"## {heading}\n\n| File | Description | Type | Author | As of | Links |\n|---|---|---|---|---|---|")
    for f in shown:
        meta, body = fm(os.path.join(d, f))
        links = sorted(set(re.findall(r"\[\[([a-z0-9][a-z0-9-]*)\]\]", body)))
        dangling += [(f"{kind}/{f}", l) for l in links if l not in known]
        print(f"| [{kind}/{f}]({kind}/{f}) | {meta.get('description','-')} | {meta.get('type','-')} "
              f"| {meta.get('author','-')} | {meta.get('updated','-')} | {' '.join('[['+l+']]' for l in links) or '-'} |")
    print()
if dangling:
    print("## Open links\n\nNot an error: a link without a target marks a fact that still ought to be written.\n")
    for src, l in dangling:
        print(f"- `[[{l}]]` in {src}")
    print()
log = os.path.join(root, "log.md")
if os.path.exists(log):
    heads = [(n, l.strip()[3:]) for n, l in enumerate(open(log, encoding="utf-8", errors="replace"), 1)
             if re.match(r"^## \d{4}-\d{2}-\d{2} \d{2}:\d{2} · ", l)]
    print(f"## Journal — last 20 of {len(heads)}\n")
    for n, h in heads[-20:][::-1]:
        print(f"- [log.md:{n}](log.md) {h}")
    print()
PY
}

reindex() { build_index "$ME" "Memory · $R"; build_index "$SHARED" "Swarm memory · all roles"; }

BODY="$(mktemp)"; trap 'rm -f "$BODY"' EXIT

cmd="${1:-}"; shift || true
case "$cmd" in
  note|share)
    [ $# -ge 2 ] || die "usage: brain.sh $cmd <slug> \"<description>\" < body"
    slug_ok "$1"; cat > "$BODY"
    if [ "$cmd" = "note" ]; then target="$ME/facts/$1.md"; else target="$SHARED/facts/$1.md"; fi
    if [ "$cmd" = "share" ] && [ -f "$target" ]; then
      owner="$(sed -n 's/^author: //p' "$target" | head -1)"
      [ "$owner" = "$R" ] || die "$1 belongs to $owner. Do not overwrite — pick your own slug or ask @$owner in the chat"
    fi
    guard_fact "$target" "$1" "$2" "${TYPE:-project}" "$BODY" || exit 1
    write_fm "$target" "$1" "$2" "${TYPE:-project}" "$BODY"
    reindex; echo "remembered: ${target#$KIT_ROOT/}"
    ;;
  forget)
    [ $# -ge 1 ] || die "usage: brain.sh forget <slug> [--shared]"
    slug_ok "$1"
    if [ "${2:-}" = "--shared" ]; then target="$SHARED/facts/$1.md"; else target="$ME/facts/$1.md"; fi
    [ -f "$target" ] || die "${target#$KIT_ROOT/} does not exist — nothing deleted"
    owner="$(sed -n 's/^author: //p' "$target" | head -1)"
    [ "$owner" = "$R" ] || die "$1 belongs to $owner — only the author deletes"
    rm -f "$target"; reindex; echo "deleted: ${target#$KIT_ROOT/}"
    ;;
  doc)
    [ $# -ge 2 ] || die "usage: brain.sh doc <slug> \"<description>\" < body"
    slug_ok "$1"; cat > "$BODY"; write_fm "$ME/docs/$1.md" "$1" "$2" "doc" "$BODY"
    reindex; echo "document: memory/$R/docs/$1.md"
    ;;
  handover)
    [ $# -ge 1 ] || die "usage: brain.sh handover \"<description>\" < body"
    # Never overwrite an existing handover. Two resets inside the same second are rare but real,
    # and the one that loses is the one nobody notices is gone.
    cat > "$BODY"; stamp="$(date '+%Y-%m-%d-%H%M%S')"; f="$stamp.md"; n=2
    while [ -e "$ME/handover/$f" ]; do f="$stamp-$n.md"; n=$((n + 1)); done
    write_fm "$ME/handover/$f" "handover-${f%.md}" "$1" "handover" "$BODY"
    reindex; echo "handover: memory/$R/handover/$f"
    ;;
  log)
    [ $# -ge 1 ] || die "usage: brain.sh log \"<subject>\" < body"
    cat > "$BODY"
    append() {
      [ -f "$ME/log.md" ] || printf '# Journal · %s\n\nAppend-only. Never edit — the index points at line numbers.\n' "$R" > "$ME/log.md"
      { printf '\n## %s · %s · %s\n' "$(now)" "$R" "$1"; cat "$BODY"; } >> "$ME/log.md"
    }
    with_lock "$ME/log.md.lock" append "$1"
    reindex; echo "journal: memory/$R/log.md:$(wc -l < "$ME/log.md" | tr -d ' ')"
    ;;
  recall)
    reindex
    echo "══ your memory: memory/$R/INDEX.md ══"; sed -n '4,60p' "$ME/INDEX.md"
    last="$(ls -1 "$ME/handover/"*.md 2>/dev/null | sort | tail -1 || true)"
    if [ -n "$last" ]; then echo "══ last handover: ${last#$KIT_ROOT/} ══"; sed -n '1,80p' "$last"
    else echo "══ no handover available ══"; fi
    echo "══ swarm: memory/_shared/INDEX.md ══"; sed -n '4,40p' "$SHARED/INDEX.md"
    ;;
  index) reindex; echo "indexes rebuilt: memory/$R, memory/_shared" ;;
  *) die "command: note | share | forget | doc | handover | log | recall | index" ;;
esac
