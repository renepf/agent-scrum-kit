#!/usr/bin/env bash
# Watchdog: read the real context state per session from the transcripts, write budget.md.
#
# Where the transcripts are and what they look like only the host adapter knows:
#   adapters/<host>/transcript-path.sh <session-id>  prints paths, one per line.
# If a host writes no transcripts, the role falls back to the emergency brake
# (retirement after KIT_MAX_TICKETS) — and budget.md says so.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

SPRINT="$(sprint_dir)"
PROBE="$KIT_ROOT/adapters/$KIT_HOST/transcript-path.sh"

python3 - "$SPRINT" "$KIT_WARN_TOKENS" "$KIT_STOP_TOKENS" "$PROBE" "${KIT_MAX_TICKETS:-5}" <<'PY' | atomic_write "$SPRINT/budget.md"
import json, os, subprocess, sys, datetime

sprint, warn, stop, probe, maxtickets = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), sys.argv[4], sys.argv[5]

# roster.md: | time | role | session-id | host |
rows = []
roster = os.path.join(sprint, "roster.md")
if os.path.exists(roster):
    for line in open(roster, encoding="utf-8"):
        f = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(f) >= 3 and f[0].startswith("20"):
            rows.append((f[1], f[2]))

def transcripts(sid):
    """None = the host knows no transcripts at all (adapter missing or not executable).
    Empty list = the adapter ran but found nothing for THIS id. Two different causes,
    two different messages — neither of them is a 0."""
    if not os.access(probe, os.X_OK):
        return None
    try:
        out = subprocess.run([probe, sid], capture_output=True, text=True, timeout=20)
    except Exception:
        return None
    if out.returncode != 0:
        return []
    return [p for p in out.stdout.split("\n") if p.strip() and os.path.exists(p)]

def turn(rec):
    """(context, output) of one transcript record, or None. One shape per host, each measured
    (adapters/<host>/README.md)."""
    msg = rec.get("message") if isinstance(rec.get("message"), dict) else {}
    u = msg.get("usage") or rec.get("usage") or {}
    if "input_tokens" in u:      # claude-code: input_tokens excludes the cache
        return (u["input_tokens"] + u.get("cache_read_input_tokens", 0)
                + u.get("cache_creation_input_tokens", 0), u.get("output_tokens", 0))
    if "input" in u:             # pi: input excludes cacheRead and cacheWrite
        return u["input"] + u.get("cacheRead", 0) + u.get("cacheWrite", 0), u.get("output", 0)
    m = rec.get("usageMetadata") or {}
    if "promptTokenCount" in m:  # qwen-code: promptTokenCount already contains the cached tokens
        return m["promptTokenCount"], m.get("candidatesTokenCount", 0)
    return None

def usage_for(sid):
    """Context size = the largest input state of ONE turn. Not the sum over turns."""
    paths = transcripts(sid)
    if paths is None:
        return "NOPROBE"
    if not paths:
        return None
    turns = []
    for path in paths:
        with open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                try:
                    rec = json.loads(line)
                except ValueError:
                    continue
                t = turn(rec) if isinstance(rec, dict) else None
                if t is not None:
                    turns.append(t)
    return (max(c for c, _ in turns), sum(o for _, o in turns)) if turns else "NOUSAGE"

def num(n):
    return f"{n:,}".replace(",", " ")

print(f"# budget · {os.path.basename(sprint)}")
print()
print("GENERATED by bin/budget.sh. Do not edit by hand.")
print(f"As of: {datetime.datetime.now():%Y-%m-%d %H:%M} · warning from {num(warn)} · stop from {num(stop)}")
print()
print("Context = the largest input state of ONE turn (input + cache_read + cache_creation),")
print("not the sum over all turns.")
print("Per host: qwen-code promptTokenCount (contains the cache), pi input + cacheRead + cacheWrite.")
print()
print("| Role | Session-ID | Context | Output total | State |")
print("|---|---|---|---|---|")

stops = []
for role, sid in rows:
    res = usage_for(sid)
    if res == "NOPROBE":
        print(f"| {role} | `{sid}` | UNKNOWN | UNKNOWN | host writes no transcripts — emergency brake after {maxtickets} tickets |")
        continue
    if res == "NOUSAGE":
        print(f"| {role} | `{sid}` | UNKNOWN | UNKNOWN | transcript has no usage record this kit knows — not read as 0 |")
        continue
    if res is None:
        print(f"| {role} | `{sid}` | UNKNOWN | UNKNOWN | transcript not found — do not read as 0 |")
        continue
    ctx, out = res
    if ctx >= stop:
        state = "**STOP** — clear the context at the ticket boundary"
        stops.append(role)
    elif ctx >= warn:
        state = "warning — take no new ticket"
    else:
        state = "ok"
    print(f"| {role} | `{sid}` | {num(ctx)} | {num(out)} | {state} |")

print()
for role in stops:
    print(f"STOP {role}")
if not stops:
    print("_no stop flag set_")
PY

echo "budget.md written:"
grep -E '^\| [a-z]' "$SPRINT/budget.md" || true
