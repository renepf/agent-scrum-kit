#!/usr/bin/env bash
# Rebuilds sprints/<active>/INDEX.md completely from all chat/*.md.
# GENERATED, never edited by hand. Deterministic: same input, same output.
# Atomic: write to a temporary file first, then rename — a half-written index
# can never be read.
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

SPRINT="$(sprint_dir)"
cd "$SPRINT"

{
  echo "# INDEX — $(basename "$SPRINT")"
  echo
  echo "GENERATED by bin/reindex.sh. Do not edit by hand."
  echo
  echo "| Time | Role | Ticket | Subject | Source |"
  echo "|---|---|---|---|---|"
  # Head lines have the form:  ## <date> <time> · <role> · <ticket> · <subject>
  # Only real entry heads '## <date> <time> · …'. Sub-headings inside the body of an
  # entry also start with '## ' and must NOT enter the index.
  # A fresh sprint has no chat file yet: grep then ends with exit code 2, and pipefail
  # would silently abort the whole script. No entry is a valid index, though.
  { grep -Hn -E '^## [0-9]{4}-[0-9]{2}-[0-9]{2} [0-9]{2}:[0-9]{2} · ' chat/*.md 2>/dev/null || true; } \
    | sed 's/^\(chat\/[^:]*\):\([0-9]*\):## /\1\t\2\t/' \
    | awk -F'\t' '{
        n = split($3, f, / · /)
        time = f[1]; role = (n>1 ? f[2] : "?"); ticket = (n>2 ? f[3] : "-")
        subject = ""
        for (i = 4; i <= n; i++) subject = subject (i>4 ? " · " : "") f[i]
        if (subject == "") subject = "-"
        printf "%s\t%s\t%09d\t| %s | %s | %s | %s | %s:%s |\n", time, $1, $2, time, role, ticket, subject, $1, $2
      }' \
    | sort \
    | cut -f4-
} | atomic_write "$SPRINT/INDEX.md"

echo "INDEX.md rebuilt: $(grep -c '^| [0-9]' "$SPRINT/INDEX.md" || true) entries"
