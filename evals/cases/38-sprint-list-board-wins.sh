#!/usr/bin/env bash
CASE_DESC="the local ticket list: generated from the board, rebuilt after every status change, and the board wins a disagreement"
CASE_KIND="static"
CASE_HOST=""
source "$(dirname "${BASH_SOURCE[0]}")/../lib/harness.sh"
sandbox; trap sandbox_cleanup EXIT
SPRINT="$(sandbox_sprint)"
LIST="$SPRINT/tickets.md"
errors=""

sandbox_issue 41 '{"title":"the first ticket","labels":["sprint:current","status:backlog"]}'
sandbox_issue 42 '{"title":"the second ticket","labels":["sprint:current","status:in-progress","owner:engineer-a"]}'
sandbox_issue 43 '{"title":"a foreign ticket","labels":["status:backlog"]}'

# 1. a rebuild writes the list, one row per sprint ticket, and nothing else
KIT_ROLE=product-owner "$BIN/sprint-list.sh" > /dev/null 2>&1 || errors="$errors 1:exit=$?"
[ -f "$LIST" ] || errors="$errors 1:no-file"
grep -q 'GENERATED by bin/sprint-list.sh' "$LIST" || errors="$errors 1:no-header"
rows="$(grep -c '^| #[0-9]' "$LIST" || true)"
[ "$rows" = "2" ] || errors="$errors 1:rows=$rows"
grep -q '^| #41 | the first ticket | backlog | — |' "$LIST" || errors="$errors 1:row41='$(grep '^| #41' "$LIST")'"
grep -q '^| #42 | the second ticket | in-progress | engineer-a |' "$LIST" || errors="$errors 1:row42='$(grep '^| #42' "$LIST")'"
grep -q '#43' "$LIST" && errors="$errors 1:foreign-ticket-listed"

# 2. a status change rebuilds the list on its own — nobody has to remember it
sandbox_plannable 41 'src/a/**'
KIT_ROLE=product-owner "$BIN/status.sh" 41 planned > /dev/null 2>&1 || errors="$errors 2:status=$?"
grep -q '^| #41 | the first ticket | planned | — |' "$LIST" || errors="$errors 2:row41='$(grep '^| #41' "$LIST")'"

# 3. the board wins: a hand-edited row is corrected, and the disagreement is named
python3 - "$LIST" <<'PY'
import sys
p = sys.argv[1]
s = open(p).read().replace("| #42 | the second ticket | in-progress |", "| #42 | the second ticket | done |")
open(p, "w").write(s)
PY
KIT_ROLE=product-owner "$BIN/sprint-list.sh" > /dev/null 2>&1 || errors="$errors 3:exit=$?"
grep -q '^| #42 | the second ticket | in-progress | engineer-a |' "$LIST" || errors="$errors 3:not-corrected"
grep -q 'DEVIATION' "$LIST" || errors="$errors 3:deviation-not-named"
grep -q '^- #42 list `done`' "$LIST" || errors="$errors 3:deviation-line='$(grep '^- #' "$LIST" | tr '\n' ' ')'"

# 4. a clean rebuild names no deviation
KIT_ROLE=product-owner "$BIN/sprint-list.sh" > /dev/null 2>&1
grep -q 'DEVIATION' "$LIST" && errors="$errors 4:deviation-without-cause"

# 5. a failed board read leaves the list untouched — a failure is not a state
before="$(cat "$LIST")"
chmod 000 "$SANDBOX/issues.json"
msg="$(KIT_ROLE=product-owner "$BIN/sprint-list.sh" 2>&1 >/dev/null)"
rc=$?
chmod 644 "$SANDBOX/issues.json"
[ "$rc" != "0" ] || errors="$errors 5:exit=0"
[ "$before" = "$(cat "$LIST")" ] || errors="$errors 5:list-changed"
# The message has to name the READ. Swallowing the read error and dying later over empty JSON
# also exits non-zero — that would leave the rule untested (the probe stayed green and silent).
case "$msg" in *"sprint tickets not readable"*) ;; *) errors="$errors 5:msg='$msg'" ;; esac

observe "rebuild: $rows rows, the foreign ticket stays out · after planned #41 shows 'planned' · a hand-edited row is corrected and the deviation named · a clean rebuild names none · a failed read exits $rc, changes nothing and says '$(printf '%s' "$msg" | head -c 40)'${errors:+ · ERRORS:$errors}"
echo "OBSERVED: $OBSERVED"
[ -z "$errors" ]
