#!/usr/bin/env bash
CASE_DESC="the memory index is generated: one line per entry, deterministic, open [[links]] visible"
CASE_KIND="static"
CASE_HOST=""
source "$(dirname "${BASH_SOURCE[0]}")/../lib/harness.sh"
sandbox; trap sandbox_cleanup EXIT
export KIT_ROLE=engineer-b
TYPE=feedback "$BIN/brain.sh" note mutation-per-guarantee "green after removing a guard means a test is missing" <<'EOF' > /dev/null
One mutation per guarantee. See [[empty-start-state]] and [[does-not-exist-yet]].
EOF
TYPE=project "$BIN/brain.sh" note empty-start-state "a test with an empty state often does not see the real path" <<'EOF' > /dev/null
Measured 2026-09-10.
EOF
I="$SANDBOX/memory/engineer-b/INDEX.md"
lines="$(grep -c '^| \[facts/' "$I")"
h1="$(shasum "$I" | cut -d' ' -f1)"
KIT_ROLE=engineer-b "$BIN/brain.sh" index > /dev/null
h2="$(shasum "$I" | cut -d' ' -f1)"
open_link="$(grep -c '`\[\[does-not-exist-yet\]\]`' "$I" || true)"
resolved="$(grep -c '`\[\[empty-start-state\]\]`' "$I" || true)"
head_line="$(grep -c 'GENERATED by bin/brain.sh' "$I")"
errors=""
[ "$lines" = 2 ] || errors="$errors lines=$lines"
[ "$h1" = "$h2" ] || errors="$errors not-deterministic"
[ "$open_link" = 1 ] || errors="$errors open-link-not-listed"
[ "$resolved" = 0 ] || errors="$errors aufgeloester-Verweis-als-open_link-gelistet"
[ "$head_line" = 1 ] || errors="$errors no-GENERATED-header"
observe "2 facts → $lines index lines · rebuild identical: $([ "$h1" = "$h2" ] && echo yes || echo NO) · open: [[does-not-exist-yet]] ($open_link), not open: [[empty-start-state]]${errors:+ · ERRORS:$errors}"
echo "OBSERVED: $OBSERVED"
[ -z "$errors" ]
